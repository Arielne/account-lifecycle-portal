-- V14: lịch sử trạng thái tài khoản (module account, spec phiếu mục 3.3, T5), dùng cho Vòng đời tài khoản (CN-10).
-- Mỗi lần đổi trạng thái qua State pattern ghi 1 dòng trong cùng transaction; job Ngủ đông (CN-25) cũng phải ghi.
CREATE TABLE app.account_status_history (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  bigint      NOT NULL REFERENCES app.account (id),
    -- Rỗng khi tài khoản vừa được tạo.
    from_status varchar(20)
        CHECK (from_status IN ('PENDING_OPEN', 'ACTIVE', 'BLOCKED', 'DORMANT', 'CLOSED')),
    to_status   varchar(20) NOT NULL
        CHECK (to_status IN ('PENDING_OPEN', 'ACTIVE', 'BLOCKED', 'DORMANT', 'CLOSED')),
    -- Rỗng khi job Ngủ đông chuyển.
    ticket_id   bigint      REFERENCES app.ticket (id),
    -- Người tạo phiếu (lúc tạo, hủy) hoặc người duyệt; rỗng là Hệ thống.
    changed_by  bigint      REFERENCES app.employee (id),
    changed_at  timestamptz NOT NULL DEFAULT now()
);

-- Vòng đời của một tài khoản đọc theo thời gian.
CREATE INDEX idx_account_status_history_account ON app.account_status_history (account_id, changed_at);