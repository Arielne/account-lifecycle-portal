-- V6: audit log (module audit) và outbox_event (module notification, Outbox pattern).

CREATE TABLE app.audit_log (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at timestamptz  NOT NULL,
    -- Rỗng khi hành động do hệ thống làm (ví dụ job Ngủ đông).
    employee_id bigint       REFERENCES app.employee (id),
    action      varchar(50)  NOT NULL,
    object_type varchar(50)  NOT NULL,
    object_id   varchar(50)  NOT NULL,
    description text         NOT NULL,
    ip_address  varchar(45),
    -- Giá trị trước và sau khi sửa, lưu dạng JSON.
    changes     jsonb,
    request_id  varchar(64),
    source      varchar(100)
);

-- Outbox: sự kiện được ghi vào bảng này cùng transaction với dữ liệu nghiệp vụ,
-- sau đó mới gửi sang Kafka; published_at rỗng nghĩa là chưa gửi.
CREATE TABLE app.outbox_event (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_type varchar(50) NOT NULL,
    aggregate_id   varchar(50) NOT NULL,
    event_type     varchar(50) NOT NULL,
    payload        jsonb       NOT NULL,
    created_at     timestamptz NOT NULL DEFAULT now(),
    published_at   timestamptz
);