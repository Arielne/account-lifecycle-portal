-- V3: khách hàng (module customer), tài khoản (module account) và sequence sinh số tài khoản.

CREATE TABLE app.customer (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- CCCD đủ 12 chữ số; UNIQUE nên Postgres tự tạo index, tìm theo CCCD nhanh.
    cccd           char(12)     NOT NULL UNIQUE,
    full_name      varchar(100) NOT NULL,
    date_of_birth  date         NOT NULL,
    gender         varchar(10),
    id_issue_date  date         NOT NULL,
    id_issue_place varchar(100) NOT NULL,
    phone          varchar(11)  NOT NULL,
    email          varchar(150) NOT NULL,
    address        varchar(255) NOT NULL,
    branch_id      bigint       NOT NULL REFERENCES app.branch (id),
    created_at     timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE app.account (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number      varchar(10) NOT NULL UNIQUE,
    customer_id         bigint      NOT NULL REFERENCES app.customer (id),
    account_type_id     bigint      NOT NULL REFERENCES app.account_type (id),
    branch_id           bigint      NOT NULL REFERENCES app.branch (id),
    -- 5 trạng thái của tài khoản; database chặn giá trị khác, là lớp chặn thứ hai sau State pattern.
    status              varchar(20) NOT NULL
        CHECK (status IN ('PENDING_OPEN', 'ACTIVE', 'BLOCKED', 'DORMANT', 'CLOSED')),
    opened_at           date,
    closed_at           date,
    -- Ngày giao dịch gần nhất: lấy từ dữ liệu mẫu (giả lập core banking), job Ngủ đông dựa vào cột này.
    last_transaction_at date        NOT NULL,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);

-- Màn danh sách và job Ngủ đông lọc tài khoản theo trạng thái.
CREATE INDEX idx_account_status ON app.account (status);

-- Số tài khoản 10 chữ số. Sequence bắt đầu từ 1030000001; dữ liệu mẫu dùng dải 1020000001 trở đi nên không trùng.
CREATE SEQUENCE app.account_number_seq START WITH 1030000001 MAXVALUE 9999999999;