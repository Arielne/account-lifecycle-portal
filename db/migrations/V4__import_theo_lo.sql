-- V4: import theo lô (module importbatch).
-- Import chạy nền chỉ ghi vào 2 bảng này; khách hàng và tài khoản chỉ được tạo khi kiểm soát viên duyệt phiếu lô.

CREATE TABLE app.import_batch (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name       varchar(255) NOT NULL,
    -- Tên file lưu trên Supabase Storage (UUID), khác tên file gốc người dùng tải lên.
    storage_key     varchar(255) NOT NULL UNIQUE,
    requesting_unit varchar(150),
    status          varchar(20)  NOT NULL CHECK (status IN ('CHECKING', 'CHECKED', 'SUBMITTED')),
    total_rows      int          NOT NULL,
    valid_rows      int          NOT NULL,
    error_rows      int          NOT NULL,
    created_by      bigint       NOT NULL REFERENCES app.employee (id),
    created_at      timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE app.import_batch_row (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_batch_id   bigint       NOT NULL REFERENCES app.import_batch (id),
    row_number        int          NOT NULL,
    -- Các cột dữ liệu đọc từ Excel được để rỗng: dòng lỗi có thể thiếu ô, sai kiểu (ngày không hợp lệ)
    -- hoặc quá dài so với cột; khi đó app ghi rỗng và nêu lý do ở error_reason.
    -- Dòng VALID, CREATED thì app đã kiểm tra đủ dữ liệu trước khi ghi.
    full_name         varchar(100),
    date_of_birth     date,
    gender            varchar(10),
    cccd              char(12),
    id_issue_date     date,
    id_issue_place    varchar(100),
    phone             varchar(11),
    email             varchar(150),
    address           varchar(255),
    account_type_code varchar(10),
    result            varchar(20)  NOT NULL CHECK (result IN ('VALID', 'ERROR', 'EXCLUDED', 'CREATED')),
    error_reason      varchar(255),
    -- Tài khoản được tạo từ dòng này khi phiếu lô được duyệt; mỗi tài khoản ứng với tối đa 1 dòng.
    account_id        bigint       UNIQUE REFERENCES app.account (id),
    mail_sent_at      timestamptz
);