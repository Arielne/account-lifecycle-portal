-- V1: danh mục chi nhánh và loại tài khoản (module catalog).
-- Schema app do Flyway tự tạo trước khi chạy script đầu tiên (spring.flyway.schemas=app).
-- Khóa chính dùng IDENTITY: database tự tăng id khi INSERT không ghi id.

CREATE TABLE app.branch (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       varchar(10)  NOT NULL UNIQUE,
    name       varchar(100) NOT NULL,
    address    varchar(255) NOT NULL,
    phone      varchar(11)  NOT NULL,
    created_at timestamptz  NOT NULL DEFAULT now(),
    updated_at timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE app.account_type (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                 varchar(10)  NOT NULL UNIQUE,
    name                 varchar(100) NOT NULL,
    description          varchar(255),
    -- Số tháng không giao dịch thì job chuyển tài khoản sang Ngủ đông.
    dormant_after_months int          NOT NULL,
    created_at           timestamptz  NOT NULL DEFAULT now(),
    updated_at           timestamptz  NOT NULL DEFAULT now()
);