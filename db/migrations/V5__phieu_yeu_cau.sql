-- V5: phiếu yêu cầu, giấy tờ đính kèm, lịch sử xử lý phiếu (module ticket) và sequence sinh mã phiếu.

CREATE TABLE app.ticket (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Mã dạng PYC-2026-0001: app ghép năm với số lấy từ app.ticket_code_seq.
    code                varchar(14) NOT NULL UNIQUE,
    type                varchar(20) NOT NULL
        CHECK (type IN ('MO_TAI_KHOAN', 'PHONG_TOA', 'GO_PHONG_TOA', 'DONG_TAI_KHOAN', 'MO_TK_THEO_LO')),
    status              varchar(20) NOT NULL
        CHECK (status IN ('PENDING_APPROVAL', 'REJECTED', 'APPROVED', 'COMPLETED', 'CANCELLED')),
    -- Phiếu lô không gắn với một tài khoản nên account_id rỗng; phiếu lô gắn với đúng 1 import_batch.
    account_id          bigint      REFERENCES app.account (id),
    import_batch_id     bigint      UNIQUE REFERENCES app.import_batch (id),
    branch_id           bigint      NOT NULL REFERENCES app.branch (id),
    created_by          bigint      NOT NULL REFERENCES app.employee (id),
    approved_by         bigint      REFERENCES app.employee (id),
    from_status         varchar(20),
    to_status           varchar(20),
    reason              text        NOT NULL,
    reject_reason       text,
    submit_count        int         NOT NULL,
    process_instance_id varchar(64) NOT NULL,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);

-- Màn Phiếu chờ duyệt và Tất cả phiếu lọc theo trạng thái.
CREATE INDEX idx_ticket_status ON app.ticket (status);

-- QT-03: mỗi tài khoản chỉ có tối đa 1 phiếu đang mở (Chờ duyệt hoặc Bị từ chối).
-- Index UNIQUE có điều kiện: chỉ xét các dòng thỏa WHERE, nên phiếu đã xong hay đã hủy không bị tính.
CREATE UNIQUE INDEX uq_ticket_open_per_account ON app.ticket (account_id)
    WHERE status IN ('PENDING_APPROVAL', 'REJECTED');

-- Phần số của mã phiếu; không đếm lại theo năm nên mã không bao giờ trùng.
CREATE SEQUENCE app.ticket_code_seq START WITH 1;

CREATE TABLE app.attachment (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id     bigint       NOT NULL REFERENCES app.ticket (id),
    original_name varchar(255) NOT NULL,
    -- Tên lưu trên Supabase Storage là UUID (QT-10).
    storage_key   varchar(255) NOT NULL UNIQUE,
    content_type  varchar(100) NOT NULL,
    size_bytes    bigint       NOT NULL,
    uploaded_by   bigint       NOT NULL REFERENCES app.employee (id),
    uploaded_at   timestamptz  NOT NULL
);

CREATE TABLE app.ticket_history (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id   bigint      NOT NULL REFERENCES app.ticket (id),
    action      varchar(30) NOT NULL,
    from_status varchar(20),
    to_status   varchar(20),
    -- Rỗng khi bước do hệ thống tự làm, không phải người.
    actor_id    bigint      REFERENCES app.employee (id),
    note        text,
    created_at  timestamptz NOT NULL DEFAULT now()
);