-- V2: hồ sơ nhân viên (module employee).
-- Role không lưu ở đây, chỉ lưu ở KeyCloak. keycloak_id nối hồ sơ này với tài khoản KeyCloak.

CREATE TABLE app.employee (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    keycloak_id uuid         NOT NULL UNIQUE,
    email       varchar(150) NOT NULL UNIQUE,
    full_name   varchar(100) NOT NULL,
    -- Rỗng khi nhân viên mới tự đăng ký, chưa được Admin gán chi nhánh.
    branch_id   bigint       REFERENCES app.branch (id),
    status      varchar(20)  NOT NULL CHECK (status IN ('ACTIVE', 'LOCKED')),
    created_at  timestamptz  NOT NULL DEFAULT now(),
    updated_at  timestamptz  NOT NULL DEFAULT now()
);